READ_SYS = (
    "너는 딥리서치 팀의 조사관이다. 너는 네 절 하나만 책임진다. 다른 절은 신경 쓰지 마라. "
    "긴 영문 문서를 읽고, 네 절에 쓸 수 있는 사실만 한국어 메모로 추린다. "
    "문서에 없는 말을 지어내면 그 즉시 실패다.\n" + KOREAN_RULE
)


def read_one_user(question: str, section: str, role: str, title: str, group: str,
                  body: str, neighbors: list[str], budget_left: int) -> str:
    nb = "\n".join(neighbors) if neighbors else "(링크로 이어진 문서가 없다)"
    return f"""전체 질문: {question}
내가 맡은 절: {section} ({role})

지금 읽는 문서: «{title}» — {group} 서고
────────────────────────────────
{body}
────────────────────────────────

이 문서에서 이어지는 문서 카드 (앞으로 {budget_left}건 더 읽을 수 있다):
{nb}

할 일:
1. 이 문서가 **내 절**에 쓸모가 있는지 판단한다. 내 절에 **한 문장이라도 보탤 수 있으면 관련 있음**이다.
   전혀 쓸 말이 없을 때만 관련 없음으로 적는다.
2. 쓸모가 있으면 내 절에 넣을 사실을 메모로 추린다. 숫자·연도·연구자 이름·비판 내용처럼 **원고에 그대로 인용할 수 있는 알맹이**를 남긴다. 400~800자.
3. 다음에 읽을 문서를 위 카드에서 하나 고른다. 내 절에 가장 보탬이 될 것으로. 고를 게 없으면 null.

출력 (JSON 객체 하나):
{{"관련": true/false, "메모": "한국어 메모 (관련 없으면 빈 문자열)", "다음": "영문 문서 제목 또는 null", "이유": "다음 문서를 고른 까닭 한 문장"}}"""


# ── ③ 조사관 · 절 원고 쓰기 ───────────────────────────────
# 인용 규칙 — 팀과 대조군이 **같은 문자열**을 쓴다.
# 따로 쓰면 "프롬프트가 달라서 진 것"이라는 반론이 성립한다 (과제 4단계: 공정한 대조군).
CITE_RULES = """★ **한 문장에 사실 하나. 그 문장 끝에 근거 «문서 제목».** 인용 없는 문장은 근거 없는 주장이라 버려진다.
★ 본보기:
   ○ 그랜트는 MBTI의 예측력을 뒷받침하는 증거가 없다고 지적한다 «Myers–Briggs Type Indicator».
   ○ 바넘 효과는 모호한 성격 묘사를 자신에게 들어맞는다고 믿게 만든다 «Barnum effect».
   ✗ MBTI는 널리 쓰이지만 비판도 많다.              ← 근거가 없다. 이런 문장은 쓰지 마라.
   ✗ 이러한 점에서 궁합론은 비판받을 수 있다 «Pseudoscience».
        ← **메모에 없는 네 추론이다. «» 를 붙인다고 근거가 되지 않는다. 통째로 지워라.**
★ 붙일 근거가 마땅치 않아 문장을 손보고 싶어지면, 손보지 말고 **지워라**.
   짧고 전부 근거 있는 원고가, 길고 절반이 추측인 원고보다 낫다.
★ 다 쓴 뒤 문장을 하나씩 확인한다. «» 없이 끝나는 문장이 남아 있으면 근거를 붙이거나 지운다."""


WRITE_SYS = (
    "너는 딥리서치 팀의 조사관이다. 네가 읽은 것만 가지고 네 절의 원고를 쓴다. "
    "요약문이 아니라 보고서에 그대로 들어갈 **완성된 절 원고**다.\n" + KOREAN_RULE
)


def write_user(question: str, section: str, role: str, memos: list[tuple[str, str]],
               prev: str = "", missing: str = "", strict: bool = False,
               fabricated: list[str] | None = None) -> str:
    body = "\n\n".join(f"[«{t}» 에서 읽은 메모]\n{m}" for t, m in memos)
    allowed = ", ".join(f"«{t}»" for t, _ in memos) or "(없음)"
    again = ""
    if prev:
        again = f"""
이 절은 **다시 쓰는 것**이다. 점검에서 되돌아왔다.
직전 원고:
{prev[:2000]}
지적받은 부족한 점: {missing}
이번에는 그 구멍을 메워라. 새로 읽은 메모를 반드시 반영한다.
"""
    strict_rule = (
        "\n⚠ 직전 시도에서 «문서 제목» 을 하나도 붙이지 않았다. 그 원고는 근거 없는 글로 버려진다.\n\n"
        if strict else ""
    )
    if fabricated:
        bad = ", ".join(f"«{d}»" for d in fabricated)
        strict_rule += (
            f"\n⚠ 직전 시도에서 {bad} 를 인용했다. 너는 그 문서를 읽지 않았다. 이것은 허위 인용이고, "
            "하나만 있어도 보고서 전체가 탈락한다.\n"
            "그 문장들을 **통째로 지워라**. 짧아져도 된다.\n"
            "다른 문서 이름으로 바꿔 달지 마라. 읽지 않은 내용에 엉뚱한 출처를 붙이는 것은 "
            "허위 인용보다 나쁘다 — 지표에 잡히지도 않는다.\n\n"
        )
    return f"""전체 질문: {question}
내가 맡은 절: {section} ({role})
{again}{strict_rule}
내가 읽은 문서에서 추린 메모:

{body}

이 절의 원고를 한국어로 써라. 가장 중요한 규칙부터:

{CITE_RULES}

- 인용해도 되는 문서는 이것뿐이다: {allowed}
  여기 없는 문서를 «» 안에 쓰면 허위 인용으로 잡힌다. 절대 쓰지 마라.
- 메모에 없는 사실을 지어내지 마라. 이음말·마무리 문장으로 분량을 채우지 마라.
- 600~1000자. 소제목 없이 문단으로만.
- 마지막에 스스로 신고한다: 이 절이 질문에 답하기에 충분한가, 부족하면 무엇이 더 필요한가.

출력 (JSON 객체 하나):
{{"원고": "한국어 절 원고", "충분": true/false, "부족": "부족한 점 한두 문장 (충분하면 빈 문자열)"}}"""


