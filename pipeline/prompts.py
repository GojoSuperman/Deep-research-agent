def plan_user(question: str, n: int, cards: list[str], *, role: bool) -> str:
    role_rule = (
        '- "역할"은 그 절을 맡을 조사관의 성격이다. 큰그림/시간순/인물/원인/비교 중에서 절에 맞게 골라 "○○ 담당" 형태로 쓴다.'
        if role else
        '- "역할"은 전부 "담당" 으로 통일한다.'
    )
    return f"""질문: {question}

아래는 조사 가능한 문서 {len(cards)}건의 카드다. 제목과 앞머리만 있다.

{chr(10).join(cards)}

이 질문에 답하는 한국어 보고서를 {n}개 절로 나눠라. 규칙:

- 절끼리 겹치지 않게 서로 다른 갈래를 맡긴다. 같은 이야기를 두 절이 하면 실패다.
- 질문에 답하려면 반드시 다뤄야 할 갈래를 우선한다. 곁가지는 버린다.
- "시작문서"는 위 카드 목록에 **있는 제목을 글자 그대로** 적는다. 새로 지어내면 조사관이 헛걸음한다.
- 절마다 시작문서를 다르게 준다.
{role_rule}
- "절"(절 제목)은 한국어로, 무엇을 다루는 절인지 드러나게 쓴다.

출력 형식 (JSON 객체 하나):
{{"목차": [{{"절": "한국어 절 제목", "역할": "...", "시작문서": "영문 문서 제목", "이유": "이 문서에서 시작하는 까닭 한 문장"}}]}}"""


